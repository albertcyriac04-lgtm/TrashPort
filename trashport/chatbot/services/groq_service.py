import logging
from django.conf import settings
from django.core.cache import cache
from asgiref.sync import sync_to_async
import openai
from openai import AsyncOpenAI

logger = logging.getLogger(__name__)

class RateLimitError(Exception):
    pass

def _incr_and_expire(key, ttl):
    """
    Attempts to increment the key using django cache.
    Uses the add + incr pattern which is cross-compatible with LocMemCache and RedisCache.
    """
    added = cache.add(key, 1, timeout=ttl)
    if added:
        return 1
    try:
        val = cache.incr(key)
    except ValueError:
        # Fallback if key expired between add and incr
        cache.set(key, 1, timeout=ttl)
        val = 1
    return val

def _sync_check_rate_limit(user_id):
    rpm_key = f"chatbot:rpm:{user_id}"
    daily_key = f"chatbot:daily:{user_id}"
    global_key = "chatbot:global:rpm"

    rpm_val = _incr_and_expire(rpm_key, 60)
    if rpm_val > 5:
        raise RateLimitError("Rate limit exceeded: max 5 requests per minute.")

    daily_val = _incr_and_expire(daily_key, 86400)
    if daily_val > 100:
        raise RateLimitError("Daily rate limit exceeded: max 100 requests per day.")

    global_val = _incr_and_expire(global_key, 60)
    if global_val > 25:
        raise RateLimitError("Global rate limit exceeded: please try again in a minute.")

async def check_rate_limit(user_id):
    await sync_to_async(_sync_check_rate_limit)(user_id)

import json
import re

async def chat(messages: list[dict]) -> str:
    primary_model = getattr(settings, "CHATBOT_MODEL", "openai/gpt-oss-20b")
    candidate_models = [primary_model, "openai/gpt-oss-20b", "openai/gpt-oss-120b", "qwen/qwen3.6-27b"]
    # De-duplicate while preserving order
    models_to_try = list(dict.fromkeys([m for m in candidate_models if m]))

    client = AsyncOpenAI(api_key=settings.GROQ_API_KEY, base_url="https://api.groq.com/openai/v1", max_retries=0)

    def _clean_content(content: str) -> str:
        if not content:
            return "{}"
        # Strip thinking tags if generated by reasoning models
        cleaned = re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL).strip()
        return cleaned or content

    last_error = None
    for model_name in models_to_try:
        try:
            response = await client.chat.completions.create(
                messages=messages,
                model=model_name,
                max_tokens=settings.CHATBOT_MAX_TOKENS,
                temperature=0.3,
                stream=False,
            )
            raw = response.choices[0].message.content or "{}"
            return _clean_content(raw)
        except openai.RateLimitError as e:
            logger.warning(f"Groq RateLimitError on model {model_name}: {e}. Trying fallback model...")
            last_error = e
            continue
        except openai.APIError as e:
            # Check if failed_generation contains the model output (e.g. tool_use_failed on openai/gpt-oss-20b)
            body = getattr(e, "body", None)
            if isinstance(body, dict):
                failed_gen = body.get("error", {}).get("failed_generation") or body.get("failed_generation")
                if failed_gen:
                    try:
                        parsed_gen = json.loads(failed_gen)
                        if "arguments" in parsed_gen and isinstance(parsed_gen["arguments"], dict):
                            logger.info(f"Extracted valid arguments JSON from failed_generation on model {model_name}")
                            return json.dumps(parsed_gen["arguments"])
                        elif "arguments" in parsed_gen and isinstance(parsed_gen["arguments"], str):
                            logger.info(f"Extracted arguments string from failed_generation on model {model_name}")
                            return parsed_gen["arguments"]
                        return failed_gen
                    except Exception:
                        if isinstance(failed_gen, str) and failed_gen.strip().startswith("{"):
                            return failed_gen

            # Check for rate limit embedded in API error code 429
            if getattr(e, "status_code", None) == 429 or "rate_limit" in str(e).lower():
                logger.warning(f"Groq 429 on model {model_name}: {e}. Trying fallback model...")
                last_error = e
                continue
            logger.error(f"Groq APIError on model {model_name}: {e}")
            last_error = e
            continue
        except Exception as e:
            logger.error(f"Unexpected Groq chat completion error on model {model_name}: {e}", exc_info=True)
            last_error = e
            continue

    logger.error(f"All Groq models failed. Last error: {last_error}")
    return '{"type": "text", "message": "Service unavailable. Please try again."}'


async def log_interaction(user, user_message, raw, parsed, was_valid=True, action_taken="", error=""):
    """
    Logs a chatbot interaction to the ChatLog model for monitoring and debugging.
    Import is inside the function to avoid circular imports.
    """
    from trashport.chatbot.models import ChatLog

    @sync_to_async
    def _create_log():
        ChatLog.objects.create(
            user=user,
            user_message=user_message,
            raw_llm_output=raw,
            parsed_output=parsed,
            was_valid=was_valid,
            action_taken=action_taken,
            error_message=error,
        )

    try:
        await _create_log()
    except Exception as e:
        logger.error(f"Failed to log chat interaction: {e}", exc_info=True)
